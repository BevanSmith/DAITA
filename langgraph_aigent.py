# Node 2: Generates Python code using the LLM
def generate_code_node(state: AgentState) -> AgentState:
    df_head = ""
    df_info = ""
    if state["df"] is not None:
        # Using to_markdown() for better LLM readability
        df_head = state["df"].head().to_markdown()
        # Capturing df.info() output (which goes to stderr by default)
        buf = io.StringIO()
        state["df"].info(buf=buf)
        df_info = buf.getvalue()

    # Get the latest human message for the user_request
    user_request = ""
    for msg in reversed(state["messages"]):
        if isinstance(msg, HumanMessage):
            user_request = msg.content
            break

    # Prepare the prompt
    prompt_messages = PROMPT.format_messages(
        df_head=df_head,
        df_info=df_info,
        execution_result=state.get("execution_result", "No previous execution result."),
        user_request=user_request
    )

    # Invoke the LLM to generate code
    print("[⚙️] Generating code...")
    ai_response = llm.invoke(prompt_messages)
    generated_code = ai_response.content.strip()

    # Append LLM's thought process (optional, but good for debugging)
    # messages.append(AIMessage(content=f"Generated code:\n```python\n{generated_code}\n```"))
    print(f"[✨] Code generated:\n```python\n{generated_code}\n```")

    return {"generated_code": generated_code, "messages": state["messages"] + [AIMessage(content="Generating code for your request.")]}

