# NEW FUNCTION for Milestone 3
def should_continue(state: AgentState) -> str:
    messages = state["messages"]
    last_message = messages[-1]

    # Check if the last message is an AI message indicating code execution results
    if isinstance(last_message, AIMessage) and "Code execution result:" in last_message.content:
        # Based on the execution result, decide whether to continue generating code
        # or conclude the interaction.

        execution_result_content = state.get("execution_result", "")

        if "Execution failed" in execution_result_content:
            print("[🔄] Execution failed. Looping back to generate more code...")
            messages.append(AIMessage(content="Previous code execution failed. Let's try to fix it. Please refine your request or suggest an alternative."))
            return "generate_code" # Go back to generate more code if execution failed
        elif state.get("plot_saved_path") or state.get("csv_saved_paths"):
            # If a plot or CSV was saved, it's a good time to potentially end or ask for next steps
            print("[✅] Plot/CSV saved. Considering ending or asking for next steps.")
            messages.append(AIMessage(content="Plot or CSV file was successfully saved. What would you like to do next?"))
            # For this milestone, let's allow it to potentially end after a save action.
            # In a real agent, you might want another node to summarize or ask.
            return END
        elif "No code to execute." in execution_result_content:
             # This means generate_code_node likely failed to produce code
             print("[⚠️] No code was generated for execution. Regenerating.")
             messages.append(AIMessage(content="The LLM did not generate code. Please refine your request or provide more context."))
             return "generate_code"
        else:
            # If code ran successfully and no specific save action was detected,
            # we can decide based on common outputs.
            # If the LLM produces descriptive output, it might be done.
            # Otherwise, it might need to generate more code.
            # For now, let's assume if it executed without explicit failure, it might be trying to present info.
            print("[🤔] Code executed successfully. Deciding next step...")
            # For Milestone 3, let's assume successful execution leads to ending for now,
            # or you can loop to generate_code if you expect more interaction.
            # A more advanced agent would ask for next steps or interpret if a "final answer" was given.
            messages.append(AIMessage(content="Code executed successfully. What's next? (Type 'exit' to end)"))
            return END # For now, assume successful execution leads to end.

    # If the last message is from the user, or if we just loaded data, generate code.
    # This acts as the default routing if none of the specific conditions above match.
    print("[➡️] User message or data loaded. Proceeding to generate code.")
    return "generate_code" # Default path after data load or if a new user request comes in

# --- 5. Build the Graph ---
workflow = StateGraph(AgentState)

# Add nodes
workflow.add_node("load_data", load_data_node)
workflow.add_node("generate_code", generate_code_node)       # NEW NODE for M3
workflow.add_node("execute_code", execute_code_node)         # NEW NODE for M3

# Set entry point
workflow.set_entry_point("load_data")

# Add edges
# After loading data, always generate code
workflow.add_edge("load_data", "generate_code")

# After generating code, always execute it
workflow.add_edge("generate_code", "execute_code")

# After executing code, use a conditional edge
# The 'should_continue' function decides the next state
workflow.add_conditional_edges(
    "execute_code", # From this node
    should_continue, # Use this function to decide
    {
        "generate_code": "generate_code", # If should_continue returns "generate_code", go to generate_code node
        END: END                          # If should_continue returns END, terminate the graph
    }
)

# Compile the graph
app = workflow.compile()

