# Node 3: Executes the generated Python code
def execute_code_node(state: AgentState) -> AgentState:
    generated_code = state.get("generated_code")
    messages = state.get("messages", [])
    df = state.get("df")
    original_df = state.get("original_df")
    file_name = state.get("file_name")
    plot_saved_path = state.get("plot_saved_path")
    csv_saved_paths = state.get("csv_saved_paths", [])

    if not generated_code:
        print("[❌] Error: No code to execute.")
        messages.append(AIMessage(content="Error: No code was generated to execute."))
        return {"execution_result": "No code to execute.", "messages": messages}

    # Prepare a dictionary for local variables that the executed code can access
    # This makes 'df', 'original_df', 'file_name' available inside the exec() context
    # Also, make matplotlib.pyplot available as 'plt' for saving plots
    # And pandas as 'pd', numpy as 'np', seaborn as 'sns'
    exec_globals = {
        'df': df,
        'original_df': original_df,
        'file_name': file_name,
        'plt': plt,
        'pd': pd,
        'np': __import__('numpy'), # Import numpy on the fly
        'sns': __import__('seaborn'), # Import seaborn on the fly
        'io': io, # For potential string buffer operations within the generated code
        'sys': sys # For redirecting stdout/stderr
    }
    # Ensure any new dfs created by the agent are captured
    exec_locals = {} # Use exec_locals to capture variables modified/created by exec()

    # Capture stdout and stderr
    old_stdout = sys.stdout
    old_stderr = sys.stderr
    redirected_output = io.StringIO()
    redirected_error = io.StringIO()
    sys.stdout = redirected_output
    sys.stderr = redirected_error

    execution_result = ""
    try:
        # Execute the generated code
        exec(generated_code, exec_globals, exec_locals)

        # Get captured output
        stdout_output = redirected_output.getvalue()
        stderr_output = redirected_error.getvalue()

        if stdout_output:
            execution_result += f"Output:\n{stdout_output}\n"
        if stderr_output:
            execution_result += f"Error Output:\n{stderr_output}\n"

        # Update df and other relevant states if they were modified/created in exec_locals
        # This is CRUCIAL to persist changes made by the generated code
        if 'df' in exec_locals and isinstance(exec_locals['df'], pd.DataFrame):
            df = exec_locals['df']
            print(f"[📊] DataFrame updated by code. New shape: {df.shape}")
        # Else, if df was not explicitly modified/created in exec_locals, it remains the df from state (exec_globals['df'])
        # No need for an else here, as df already holds the initial state's df

        # Check for saved plots or CSVs (basic regex parsing, can be more robust)
        # This part assumes the LLM prints messages about saving
        plot_matches = re.findall(r"Plot saved to (.*\.png|.*\.jpg|.*\.jpeg)", execution_result)
        if plot_matches:
            plot_saved_path = plot_matches[-1] # Take the last one if multiple are saved
            print(f"[🖼️] Detected saved plot: {plot_saved_path}")

        csv_matches = re.findall(r"CSV saved to (.*\.csv)", execution_result)
        if csv_matches:
            # Append new CSV paths, avoid duplicates
            for csv_path in csv_matches:
                if csv_path not in csv_saved_paths:
                    csv_saved_paths.append(csv_path)
            print(f"[📁] Detected saved CSVs: {csv_saved_paths}")


    except Exception as e:
        execution_result = f"Execution failed: {e}\n"
        # If there's any stderr output, add it too
        stderr_output = redirected_error.getvalue()
        if stderr_output:
             execution_result += f"Error Output:\n{stderr_output}\n"
        print(f"[❌] Code execution failed: {e}")

    finally:
        # Restore stdout and stderr regardless of success or failure
        sys.stdout = old_stdout
        sys.stderr = old_stderr

    messages.append(AIMessage(content=f"Code execution result:\n```\n{execution_result}\n```"))

    return {
        "df": df, # Return the potentially updated df
        "execution_result": execution_result,
        "messages": messages,
        "plot_saved_path": plot_saved_path,
        "csv_saved_paths": csv_saved_paths
    }


